def P(x, y):
    kx, ky = g.K(x, y)
    return pcbnew.VECTOR2I(MM(kx), MM(ky))


def load_fp(lib_id):
    lib, name = lib_id.split(":")
    path = os.path.join(HW, "lib", "msdx.pretty") if lib == "msdx" else os.path.join(KICAD_FP_DIR, lib + ".pretty")
    fp = pcbnew.FootprintLoad(path, name)
    if fp is None:
        raise FileNotFoundError(lib_id)
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


_TSTAMP = re.compile(r"\(tstamp [0-9a-f-]+\)")
_REFDES = re.compile(r'\(fp_text reference "([A-Za-z]+)(\d+)"')


def _split(lines, indent):
    """Group lines into items that start at the given indent."""
    lead = " " * indent + "("
    blocks, cur = [], None
    for ln in lines:
        if (ln.startswith(lead) and not ln.startswith(lead[:-1] + " ")) or ln == ")":
            cur = [ln]
            blocks.append(cur)
        elif cur is None:
            blocks.append([ln])
        else:
            cur.append(ln)
    return blocks


def _kind(b):
    words = b[0].strip().lstrip("(").split(" ")
    k = words[0]
    if k.startswith("gr_"):
        return "gr"
    if k == "fp_text":
        return "fp_text_user" if words[1] == "user" else "fp_text_" + words[1]
    if k.startswith("fp_"):
        return "fp_gr"
    return k


def _key(b):
    text = _TSTAMP.sub("(tstamp)", "\n".join(b))
    m = _REFDES.search(text) if b[0].startswith("  (footprint") else None
    return (m.group(1), int(m.group(2)), text) if m else ("", 0, text)


def _sort_runs(blocks, sortable):
    out, i = [], 0
    while i < len(blocks):
        k = _kind(blocks[i])
        j = i
        while j < len(blocks) and _kind(blocks[j]) == k:
            j += 1
        run = blocks[i:j]
        out += sorted(run, key=_key) if k in sortable else run
        i = j
    return out


def normalise(path):
    """Make the saved board reproducible.

    pcbnew gives every item a random UUID and writes footprints, tracks,
    graphics and the items inside footprints sorted by it, so two runs of
    this script would differ in every line. Here the items are re-sorted by
    their content and the UUIDs replaced with ones derived from that content.
    Only "(tstamp ...)" tokens and the order of whole items change; the text
    KiCad wrote is otherwise kept.
    """
    lines = [ln for ln in open(path).read().split("\n") if ln.strip()]
    blocks = []
    for b in _split(lines, 2):
        if b[0].startswith("  (footprint"):
            inner = _sort_runs(_split(b[1:-1], 4), ("fp_text_user", "fp_gr", "pad", "zone"))
            b = [b[0]] + [ln for sub in inner for ln in sub] + [b[-1]]
        blocks.append(b)
    blocks = _sort_runs(blocks, ("footprint", "gr", "segment", "via", "zone"))

    seen = {}
    text_out = []
    for b in blocks:
        text = "\n".join(b)
        if "(tstamp " in text:
            h = hashlib.sha1(_TSTAMP.sub("(tstamp)", text).encode()).hexdigest()
            dup = seen[h] = seen.get(h, -1) + 1
            n = [0]

            def repl(_m):
                n[0] += 1
                return "(tstamp %s)" % uid("pcb", h, dup, n[0])
            text = _TSTAMP.sub(repl, text)
        text_out.append(text)
    open(path, "w").write("\n".join(text_out) + "\n")


def main():
    net_path = sys.argv[1]
    comps, nets = netlist.read(net_path)
    pad_net = netlist.pad_nets(nets)

    with open(PCB, "w") as f:
        f.write(HEADER % dict(title=d.TITLE, date=d.DATE, rev=d.REV, ox=g.OX, oy=g.OY + g.BOARD_L))
    with open(PRO, "w") as f:
        json.dump(project_file(), f, indent=2)
    with open(DRU, "w") as f:
        f.write(RULES)

    board = pcbnew.LoadBoard(PCB)

    # ---- nets ---------------------------------------------------------------
    netinfo = {}
    for name in sorted(nets):
        ni = pcbnew.NETINFO_ITEM(board, name)
        board.Add(ni)
        netinfo[name] = ni

    # ---- outline ------------------------------------------------------------
    for prim in g.outline():
        s = pcbnew.PCB_SHAPE(board)
        s.SetLayer(pcbnew.Edge_Cuts)
        s.SetWidth(MM(0.05))
        if prim[0] == "line":
            s.SetShape(pcbnew.SHAPE_T_SEGMENT)
            s.SetStart(P(*prim[1]))
            s.SetEnd(P(*prim[2]))
        else:
            s.SetShape(pcbnew.SHAPE_T_ARC)
            s.SetArcGeometry(P(*prim[1]), P(*prim[2]), P(*prim[3]))
        board.Add(s)

    # ---- footprints ---------------------------------------------------------
    for part in d.PARTS:
        ref = part["ref"]
        fp = load_fp(part["fp"])
        board.Add(fp)
        fp.SetPosition(P(*part["pos"]))
        fp.SetOrientationDegrees(part["rot"])
        fp.SetReference(ref)
        fp.SetValue(part["value"] + (" DNP" if part["dnp"] else ""))
        fp.SetPath(pcbnew.KIID_PATH("/" + comps[ref]["tstamp"]))
        if part["mpn"]:
            fp.SetProperty("MPN", part["mpn"])
        if part["desc"]:
            fp.SetProperty("Description", part["desc"])
        # the board is too dense for silkscreen designators: keep them on F.Fab
        fp.Reference().SetLayer(pcbnew.F_Fab)
        fp.Reference().SetTextSize(pcbnew.VECTOR2I(MM(0.5), MM(0.5)))
        fp.Reference().SetTextThickness(MM(0.08))
        fp.Reference().SetPosition(fp.GetPosition())
        fp.Reference().SetVisible(ref not in ("J1",))
        fp.Value().SetVisible(False)
        for item in fp.GraphicalItems():
            if isinstance(item, pcbnew.FP_TEXT) and ref not in ("J1", "J2"):
                item.SetVisible(False)
        for pad in fp.Pads():
            name = pad_net.get((ref, pad.GetNumber()))
            if name:
                pad.SetNet(netinfo[name])

    # ---- tracks and vias ----------------------------------------------------
    lo = layout.build()
    for net, layer, width, pts in lo.tracks:
        for a, b in zip(pts[:-1], pts[1:]):
            if a == b:
                continue
            t = pcbnew.PCB_TRACK(board)
            t.SetStart(P(*a))
            t.SetEnd(P(*b))
            t.SetWidth(MM(width))
            t.SetLayer(LAYER[layer])
            t.SetNet(netinfo[net])
            board.Add(t)
    for net, pos, dia, drill in lo.vias:
        v = pcbnew.PCB_VIA(board)
        v.SetViaType(pcbnew.VIATYPE_THROUGH)
        v.SetPosition(P(*pos))
        v.SetWidth(MM(dia))
        v.SetDrill(MM(drill))
        v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
        v.SetNet(netinfo[net])
        board.Add(v)

    # ---- zones --------------------------------------------------------------
    for z in lo.zones:
        zone = pcbnew.ZONE(board)
        zone.SetLayer(LAYER[z["layer"]])
        zone.SetNet(netinfo[z["net"]])
        zone.SetZoneName(z["name"])
        ol = zone.Outline()
        ol.NewOutline()
        for x, y in z["pts"]:
            kx, ky = g.K(x, y)
            ol.Append(MM(kx), MM(ky))
        zone.SetLocalClearance(MM(z["clearance"]))
        zone.SetMinThickness(MM(0.25))
        zone.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL if z["thermal"] else pcbnew.ZONE_CONNECTION_FULL)
        zone.SetThermalReliefGap(MM(0.2))
        zone.SetThermalReliefSpokeWidth(MM(0.3))
        zone.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
        zone.SetAssignedPriority(z["prio"])
        board.Add(zone)

    # ---- text ---------------------------------------------------------------
    def text(s, x, y, layer, size=0.8, mirror=False, thick=0.12):
        t = pcbnew.PCB_TEXT(board)
        t.SetText(s)
        t.SetPosition(P(x, y))
        t.SetLayer(layer)
        t.SetTextSize(pcbnew.VECTOR2I(MM(size), MM(size)))
        t.SetTextThickness(MM(thick))
        t.SetMirrored(mirror)
        board.Add(t)

    text("microSD Express", 0, 6.0, pcbnew.B_SilkS, 1.0, True, 0.15)
    text("to M.2 2230 Key M", 0, 7.6, pcbnew.B_SilkS, 0.8, True)
    text("rev %s  %s" % (d.REV, d.DATE), 0, 9.0, pcbnew.B_SilkS, 0.7, True, 0.1)
    text("Express (NVMe)", 0, 13.0, pcbnew.B_SilkS, 0.8, True)
    text("cards only", 0, 14.3, pcbnew.B_SilkS, 0.8, True)
    text("card side: top", 0, 17.5, pcbnew.B_SilkS, 0.7, True, 0.1)
    text("TOP VIEW. Board frame: X=0 centreline, +X to pin 1; Y=0 at mounting notch, 30 at fingers.",
         0, -2.0, pcbnew.Cmts_User, 0.6, False, 0.08)
    text("pin 1", 9.25, 31.0, pcbnew.Cmts_User, 0.5, False, 0.08)
    text("pin 75", -9.25, 31.0, pcbnew.Cmts_User, 0.5, False, 0.08)

    # ---- fill, save ---------------------------------------------------------
    filler = pcbnew.ZONE_FILLER(board)
    filler.Fill(board.Zones())
    pcbnew.SaveBoard(PCB, board)
    normalise(PCB)

    for name, r in lo.report.items():
        print(f"  pair {name:7s} P {r['p']:.3f} mm  N {r['n']:.3f} mm  skew {r['skew']:.3f} mm")
    print("wrote", PCB)


if __name__ == "__main__":
    main()
